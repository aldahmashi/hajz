"""Hajz backend developer commands (RMC style).

    python manage.py migrate              apply pending migrations
    python manage.py rollback [rev]       undo migrations (default: last one)
    python manage.py migration-status     show the current revision
    python manage.py migration-history    list all revisions
    python manage.py migration-check      fail if models and migrations differ
    python manage.py make-migration "msg" create a new empty migration
    python manage.py seed                 run the Python seeders
    python manage.py reset-db             drop and recreate the local database
    python manage.py db-status            show connection and table count
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

import pymysql
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from dotenv import load_dotenv

ROOT_DIR = Path(__file__).resolve().parent
REQUIREMENTS_PATH = ROOT_DIR / "requirements.txt"
LOCAL_ENVIRONMENTS = {"local", "test"}

RESET = "\033[0m"
BOLD = "\033[1m"
GREEN = "\033[32m"
YELLOW = "\033[33m"
RED = "\033[31m"
CYAN = "\033[36m"
GRAY = "\033[90m"


def _success(message: str) -> None:
    print(f"{GREEN}OK{RESET} {message}")


def _info(message: str) -> None:
    print(f"{CYAN}INFO{RESET} {message}")


def _warning(message: str) -> None:
    print(f"{YELLOW}WARN{RESET} {message}")


def _error(message: str) -> None:
    print(f"{RED}ERROR{RESET} {message}")


def _load_env() -> None:
    load_dotenv(ROOT_DIR / ".env")
    # Parse exactly like config.mysql_url: a stray space or newline pasted into a host
    # dashboard must not make manage.py and the app disagree on the database name.
    mysql_db = os.environ.get("MYSQL_DB", "").strip()
    parts = [part.strip() for part in mysql_db.split(":")]
    if len(parts) != 5:
        raise SystemExit("MYSQL_DB must be set as host:user:password:port:database")
    host, user, password, port, database = parts
    os.environ.setdefault("DB_HOST", host)
    os.environ.setdefault("DB_PORT", port)
    os.environ.setdefault("DB_USER", user)
    os.environ.setdefault("DB_PASSWORD", password)
    os.environ.setdefault("DB_NAME", database)


def _db_config(database: str | None = None) -> dict:
    config = {
        "host": os.environ["DB_HOST"],
        "port": int(os.environ["DB_PORT"]),
        "user": os.environ["DB_USER"],
        "password": os.environ.get("DB_PASSWORD", ""),
        "database": database,
        "autocommit": True,
        "charset": "utf8mb4",
    }
    ssl_ca = os.environ.get("DB_SSL_CA", "").strip()
    if ssl_ca:
        config["ssl"] = {"ca": ssl_ca, "check_hostname": True}
    return config


def _database_exists(database_name: str) -> bool:
    with pymysql.connect(**_db_config(None)) as connection, connection.cursor() as cursor:
        cursor.execute(
            "SELECT SCHEMA_NAME FROM information_schema.SCHEMATA WHERE SCHEMA_NAME = %s",
            (database_name,),
        )
        return cursor.fetchone() is not None


def _table_count(database_name: str) -> int:
    with pymysql.connect(**_db_config(None)) as connection, connection.cursor() as cursor:
        cursor.execute(
            "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA = %s",
            (database_name,),
        )
        return int(cursor.fetchone()[0])


def _alembic_version(database_name: str) -> str | None:
    if not _database_exists(database_name):
        return None
    with pymysql.connect(**_db_config(database_name)) as connection, connection.cursor() as cursor:
        cursor.execute("SHOW TABLES LIKE 'alembic_version'")
        if cursor.fetchone() is None:
            return None
        cursor.execute("SELECT version_num FROM alembic_version")
        row = cursor.fetchone()
        return row[0] if row else None


def _ensure_database(database_name: str) -> None:
    with pymysql.connect(**_db_config(None)) as connection, connection.cursor() as cursor:
        cursor.execute(
            f"CREATE DATABASE IF NOT EXISTS `{database_name}` "
            "CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
        )


def _alembic_config() -> Config:
    return Config(str(ROOT_DIR / "alembic.ini"))


def install_requirements(_args: argparse.Namespace) -> int:
    _info(f"Installing dependencies from {REQUIREMENTS_PATH.name}")
    return subprocess.call([sys.executable, "-m", "pip", "install", "-r", str(REQUIREMENTS_PATH)])


def migrate(args: argparse.Namespace) -> int:
    _ensure_database(os.environ["DB_NAME"])
    _info(f"Running migrations to {args.revision}")
    command.upgrade(_alembic_config(), args.revision)
    _success(f"Database migrated to {args.revision}")
    return 0


def rollback(args: argparse.Namespace) -> int:
    if not _database_exists(os.environ["DB_NAME"]):
        _error(f"Database {os.environ['DB_NAME']} does not exist. Nothing to roll back.")
        return 1
    _warning(f"Rolling database back to {args.revision}")
    command.downgrade(_alembic_config(), args.revision)
    _success(f"Database rolled back to {args.revision}")
    return 0


def migration_status(_args: argparse.Namespace) -> int:
    database_name = os.environ["DB_NAME"]
    print(f"{BOLD}Migration Status{RESET}")
    print(f"{GRAY}{'-' * 64}{RESET}")
    print(f"Database         {database_name}")
    print(f"Alembic Version  {_alembic_version(database_name) or '<not migrated>'}")
    return 0


def migration_history(_args: argparse.Namespace) -> int:
    command.history(_alembic_config(), verbose=True)
    return 0


def migration_check(_args: argparse.Namespace) -> int:
    _info("Comparing SQLAlchemy models with the migrated database")
    try:
        command.check(_alembic_config())
    except AutogenerateDiffsDetected as exc:
        _error("Models and migrations differ:")
        print(exc)
        return 1
    _success("Models match the database schema")
    return 0


def make_migration(args: argparse.Namespace) -> int:
    _info(f"Creating migration: {args.message}")
    command.revision(_alembic_config(), message=args.message, rev_id=args.rev_id)
    return 0


def seed(_args: argparse.Namespace) -> int:
    database_name = os.environ["DB_NAME"]
    if not _database_exists(database_name):
        _error(f"Database {database_name} does not exist. Run `python manage.py migrate` first.")
        return 1

    from database.seeders.runner import run_seeders

    _info("Running Python seeders")
    connection_config = _db_config(database_name)
    connection_config["autocommit"] = False
    with pymysql.connect(**connection_config) as connection:
        try:
            run_seeders(connection, logger=_success)
            connection.commit()
        except Exception as exc:
            connection.rollback()
            _error(f"Seeding failed: {exc}")
            return 1

    _success("Database seeded")
    return 0


def reset_db(_args: argparse.Namespace) -> int:
    app_env = os.environ.get("APP_ENV", "local").lower()
    if app_env not in LOCAL_ENVIRONMENTS:
        _error("reset-db is only allowed for local and test environments.")
        return 1

    database_name = os.environ["DB_NAME"]
    _warning(f"Dropping and recreating database `{database_name}`")
    with pymysql.connect(**_db_config(None)) as connection, connection.cursor() as cursor:
        cursor.execute(f"DROP DATABASE IF EXISTS `{database_name}`")
        cursor.execute(
            f"CREATE DATABASE `{database_name}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"
        )
    _success(f"Database `{database_name}` reset")
    return 0


def db_status(_args: argparse.Namespace) -> int:
    database_name = os.environ["DB_NAME"]
    exists = _database_exists(database_name)
    print(f"{BOLD}Database Status{RESET}")
    print(f"{GRAY}{'-' * 64}{RESET}")
    print(f"Host      {os.environ['DB_HOST']}:{os.environ['DB_PORT']}")
    print(f"Database  {database_name}")
    print(f"Exists    {exists}")
    print(f"Tables    {_table_count(database_name) if exists else 0}")
    print(f"Revision  {_alembic_version(database_name) or '<not migrated>'}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Hajz backend developer commands")
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("install", help="Install Python dependencies").set_defaults(func=install_requirements)

    migrate_parser = subparsers.add_parser("migrate", help="Apply migrations")
    migrate_parser.add_argument("revision", nargs="?", default="head")
    migrate_parser.set_defaults(func=migrate)

    rollback_parser = subparsers.add_parser("rollback", help="Undo migrations")
    rollback_parser.add_argument("revision", nargs="?", default="-1")
    rollback_parser.set_defaults(func=rollback)

    subparsers.add_parser("migration-status", help="Show current revision").set_defaults(func=migration_status)
    subparsers.add_parser("migration-history", help="List revisions").set_defaults(func=migration_history)
    subparsers.add_parser("migration-check", help="Compare models with database").set_defaults(func=migration_check)

    make_parser = subparsers.add_parser("make-migration", help="Create an empty migration")
    make_parser.add_argument("message")
    make_parser.add_argument("--rev-id", help="Revision id, e.g. 0007_add_x (default: random)")
    make_parser.set_defaults(func=make_migration)

    subparsers.add_parser("seed", help="Run Python seeders").set_defaults(func=seed)
    subparsers.add_parser("reset-db", help="Drop and recreate the local database").set_defaults(func=reset_db)
    subparsers.add_parser("db-status", help="Show database status").set_defaults(func=db_status)
    return parser


def main() -> int:
    _load_env()
    args = build_parser().parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
